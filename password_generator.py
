import secrets
import string

def evaluate_strength(password: str) -> str:
    """Evaluates the strength of the generated password."""
    has_upper = any(c.isupper() for c in password)
    has_lower = any(c.islower() for c in password)
    has_digit = any(c.isdigit() for c in password)
    has_symbol = any(c in string.punctuation for c in password)

    score = sum([has_upper, has_lower, has_digit, has_symbol])

    if len(password) >= 12 and score >= 3:
        return "Strong"
    elif len(password) >= 8 and score >= 2:
        return "Moderate"
    else:
        return "Weak"

def generate_password(length: int, use_digits: bool, use_symbols: bool) -> str:
    """Generates a cryptographically secure random password."""
    char_pool = string.ascii_letters

    if use_digits:
        char_pool += string.digits
    if use_symbols:
        char_pool += string.punctuation

    return "".join(secrets.choice(char_pool) for _ in range(length))

def main() -> None:
    print("=" * 50)
    print("         CLI SECURE PASSWORD GENERATOR            ")
    print("=" * 50)

    while True:
        try:
            # User configurations
            length_input = input("\nEnter desired password length (default: 12): ").strip()
            length = int(length_input) if length_input else 12

            if length < 4:
                print("Error: Password length must be at least 4 characters.")
                continue

            digits_choice = input("Include numbers (0-9)? (y/n, default: y): ").strip().lower()
            use_digits = digits_choice != "n"

            symbols_choice = input("Include special symbols (!@#$)? (y/n, default: y): ").strip().lower()
            use_symbols = symbols_choice != "n"

            count_input = input("How many passwords to generate? (default: 1): ").strip()
            count = int(count_input) if count_input else 1

            if count < 1:
                print("Error: Count must be at least 1.")
                continue

            # Display Results
            print("\n" + "-" * 50)
            print("              GENERATED PASSWORDS                 ")
            print("-" * 50)

            for index in range(1, count + 1):
                pwd = generate_password(length, use_digits, use_symbols)
                strength = evaluate_strength(pwd)
                print(f"[{index}] {pwd:<25} | Strength: {strength}")

            print("-" * 50)

        except ValueError:
            print("Error: Invalid input. Please enter numeric values for length and count.")

        choice = input("\nGenerate another batch? (y/n): ").strip().lower()
        if choice != "y":
            print("\nThank you for using Password Generator. Goodbye!\n")
            break

if __name__ == "__main__":
    main()
